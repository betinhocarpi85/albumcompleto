export type StickerType = 'normal' | 'escudo' | 'brilhante' | 'especial' | 'extra-gold' | 'extra-silver' | 'extra-bronze' | 'extra-purple' | 'coca-cola'

export interface Sticker {
  number: number   // 1-20 dentro do time, ou 1-20 na intro
  name: string
  type: StickerType
}

export interface Category {
  id: string
  code: string     // ex: "BRA", "ARG", "FWC"
  name: string
  flag?: string
  stickers: Sticker[]
}

export interface Album {
  id: string
  name: string
  year: number
  totalStickers: number
  categories: Category[]
}

// Helper: retorna o ID Ãºnico da figurinha (ex: "BRA-14")
export function stickerId(categoryCode: string, number: number): string {
  return `${categoryCode}-${number}`
}

// Helper: gera mapa de stickerID â†’ nÃºmero global sequencial (1-980)
export function buildGlobalNumberMap(album: Album): Map<string, number> {
  const map = new Map<string, number>()
  let counter = 1
  for (const cat of album.categories) {
    for (const s of cat.stickers) {
      map.set(stickerId(cat.code, s.number), counter++)
    }
  }
  return map
}

